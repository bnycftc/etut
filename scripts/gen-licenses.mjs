#!/usr/bin/env node
/**
 * Generates `src/legal/licenses.ts`: the open-source packages that end up inside the app, with
 * version and license, for "Hakkında → Açık kaynak lisansları".
 *
 * Which packages: every npm package that contributes code to the iOS JavaScript bundle, read from
 * the source map of `expo export --platform ios` (build-only tooling such as Babel or the Expo CLI
 * is not in the bundle and so not listed). Native code ships from these same packages.
 *
 *   node scripts/gen-licenses.mjs            # runs the export into a temporary folder
 *   node scripts/gen-licenses.mjs dist       # uses an existing `expo export --source-maps` output
 *
 * Re-run after adding or upgrading dependencies.
 */

import { spawnSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src', 'legal', 'licenses.ts');

function findMaps(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) out.push(...findMaps(p));
    else if (name.endsWith('.map')) out.push(p);
  }
  return out;
}

let distDir = process.argv[2] ? path.resolve(process.argv[2]) : null;
let temp = null;
if (distDir === null) {
  temp = mkdtempSync(path.join(tmpdir(), 'etut-licenses-'));
  distDir = temp;
  const cli = path.join(ROOT, 'node_modules', 'expo', 'bin', 'cli');
  const run = spawnSync(
    process.execPath,
    [cli, 'export', '--platform', 'ios', '--source-maps', '--output-dir', distDir],
    { cwd: ROOT, stdio: 'inherit', env: { ...process.env, EXPO_NO_TELEMETRY: '1' } },
  );
  if (run.status !== 0) process.exit(run.status ?? 1);
}

const packages = new Map();
for (const mapFile of findMaps(distDir)) {
  const { sources = [] } = JSON.parse(readFileSync(mapFile, 'utf8'));
  for (const source of sources) {
    const normalized = source.replace(/\\/g, '/');
    const i = normalized.lastIndexOf('node_modules/');
    if (i < 0) continue;
    const parts = normalized.slice(i + 'node_modules/'.length).split('/');
    const name = parts[0].startsWith('@') ? `${parts[0]}/${parts[1]}` : parts[0];
    const dir = normalized.slice(0, i) + 'node_modules/' + name;
    packages.set(name, dir.startsWith('/') || /^[A-Za-z]:/.test(dir) ? dir : path.join(ROOT, dir));
  }
}
if (temp !== null) rmSync(temp, { recursive: true, force: true });

function licenseOf(pkg) {
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license && typeof pkg.license.type === 'string') return pkg.license.type;
  if (Array.isArray(pkg.licenses)) return pkg.licenses.map((l) => l.type ?? l).join(' OR ');
  return 'UNKNOWN';
}

const rows = [];
for (const [name, dir] of packages) {
  let pkg;
  try {
    pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));
  } catch {
    try {
      pkg = JSON.parse(readFileSync(path.join(ROOT, 'node_modules', name, 'package.json'), 'utf8'));
    } catch {
      continue;
    }
  }
  if (pkg.name === 'etut') continue;
  rows.push({ name, version: String(pkg.version ?? ''), license: licenseOf(pkg) });
}
rows.sort((a, b) => a.name.localeCompare(b.name));

const body = rows
  .map((r) => `  { name: ${JSON.stringify(r.name)}, version: ${JSON.stringify(r.version)}, license: ${JSON.stringify(r.license)} },`)
  .join('\n');
writeFileSync(
  OUT,
  `/**
 * GENERATED by scripts/gen-licenses.mjs — do not edit by hand.
 * Open-source packages bundled into the app (from the iOS bundle's source map).
 */

export interface PackageLicense {
  name: string;
  version: string;
  license: string;
}

export const LICENSES: readonly PackageLicense[] = [
${body}
];
`,
);
console.log(`[gen-licenses] ${rows.length} packages → ${path.relative(ROOT, OUT)}`);
